\c stock_market_battles

CREATE TABLE users (
    id              INT GENERATED BY DEFAULT AS IDENTITY,
    name            VARCHAR(24) NOT NULL,
    email_address   VARCHAR(320) NOT NULL,
    pw_hash         CHAR(60) NOT NULL,
    verified        BOOLEAN NOT NULL DEFAULT FALSE,
    games_played  INT NOT NULL DEFAULT 0,
    games_won      INT NOT NULL DEFAULT 0	

    CONSTRAINT users_pk PRIMARY KEY (id),
    CONSTRAINT users_name_unique UNIQUE (name)
);

CREATE TABLE friendships (
    user_low    INT NOT NULL,
    user_high   INT NOT NULL,

    CONSTRAINT friendships_pk
        PRIMARY KEY (user_low, user_high),

    CONSTRAINT friendships_user_low_fk
        FOREIGN KEY (user_low) REFERENCES users(id)
        ON DELETE CASCADE,

    CONSTRAINT friendships_user_high_fk
        FOREIGN KEY (user_high) REFERENCES users(id)
        ON DELETE CASCADE,

    CONSTRAINT friendships_order_check
        CHECK (user_low < user_high)
);

CREATE TABLE games (
    game_code           CHAR(10) NOT NULL,
    name                VARCHAR(128),
    creation_date       TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    start_date          TIMESTAMP NOT NULL,
    length              INTERVAL NOT NULL,
    starting_balance    NUMERIC(8, 2) NOT NULL,
    created_by          INT NOT NULL,

    CONSTRAINT games_pk
        PRIMARY KEY (game_code),

    CONSTRAINT games_created_by_fk
        FOREIGN KEY (created_by) REFERENCES users(id),

    CONSTRAINT games_length_check
        CHECK (length IS NULL OR length >= INTERVAL '0'),

    CONSTRAINT games_starting_balance_check
        CHECK (starting_balance >= 0)
);

CREATE TABLE user_games (
    user_id      INT NOT NULL,
    game        CHAR(10) NOT NULL,
    tickers     VARCHAR(5)[],
    balances    NUMERIC(15, 2)[],
    real_balances NUMERIC(15, 2)[],
    joined      BOOLEAN NOT NULL DEFAULT FALSE,

    CONSTRAINT user_games_pk
        PRIMARY KEY ("user", game),

    CONSTRAINT user_games_user_fk
        FOREIGN KEY (user_id) REFERENCES users(id)
        ON DELETE CASCADE,

    CONSTRAINT user_games_game_fk
        FOREIGN KEY (game) REFERENCES games(game_code)
);

